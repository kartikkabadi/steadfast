#!/bin/bash
# Distributed by package.sh with the release origin and certificate pin filled in.
set -euo pipefail
export PATH=/usr/bin:/bin:/usr/sbin:/sbin
umask 077
SITE='@RELEASE_SITE@'
CERT='@RELEASE_CERT@'
LOCAL=''
VERIFY=false
IN_APP=false
die() { printf 'steadfast: %s\n' "$*" >&2; exit 1; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --local) [[ $# -ge 2 && -d "$2" ]] || die 'choose a local release directory'; LOCAL="$(cd "$2" && pwd)"; shift 2 ;;
    --verify-only) VERIFY=true; shift ;;
    --in-app) IN_APP=true; shift ;;
    *) die 'usage: install.sh [--local release-directory] [--verify-only]' ;;
  esac
done
[[ $EUID -ne 0 ]] || die 'run this command as your regular user. it will ask for administrator approval when ready.'
[[ "$CERT" =~ ^[A-Fa-f0-9]{40}$ ]] || die 'use the installer generated by scripts/package.sh.'
[[ "$(sysctl -n hw.optional.arm64 2>/dev/null)" == 1 ]] || die 'steadfast requires an apple silicon mac.'
OS="$(sw_vers -productVersion)"
[[ "${OS%%.*}" -ge 26 ]] || die "steadfast requires macos 26 or later. this mac runs $OS."

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
fetch() {
  if [[ -n "$LOCAL" ]]; then
    cp "$LOCAL/$1" "$2"
  else
    curl -fSsL --proto '=https' --proto-redir '=https' --connect-timeout 10 --max-time 120 --retry 2 -o "$2" "$SITE/$1"
  fi
}
fetch latest.json "$WORK/latest.json" || die 'could not read the release information. try again.'
read_value() { plutil -extract "$1" raw -o - "$WORK/latest.json"; }
VERSION="$(read_value version)" || die 'release version is missing.'
DIGEST="$(read_value sha256)" || die 'release checksum is missing.'
[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ && "$DIGEST" =~ ^[0-9a-f]{64}$ ]] || die 'the release information is invalid.'
NAME="Steadfast-$VERSION-${DIGEST:0:12}.zip"
printf 'downloading steadfast %s…\n' "$VERSION"
ZIP="$WORK/$NAME"
fetch "$NAME" "$ZIP" || die 'the download failed. try again.'
[[ "$(shasum -a 256 "$ZIP" | awk '{print $1}')" == "$DIGEST" ]] || die 'the download failed its checksum.'

zipinfo -1 "$ZIP" > "$WORK/entries" || die 'could not inspect the download.'
[[ -s "$WORK/entries" ]] || die 'the download is empty.'
while IFS= read -r entry; do
  case "$entry" in Steadfast.app/*) ;; *) die 'unexpected archive path.' ;; esac
  case "/${entry%/}/" in *\\*|*/../*|*/./*|*//*) die 'unsafe archive path.' ;; esac
done < "$WORK/entries"
zipinfo -l "$ZIP" > "$WORK/types" || die 'could not inspect the archive contents.'
if grep -Eq '^[lbcps]' "$WORK/types"; then die 'unexpected file type in the download.'; fi
ditto -x -k "$ZIP" "$WORK"
APP="$WORK/Steadfast.app"
HELPER="$APP/Contents/Resources/steadfastd"
INFO="$APP/Contents/Info.plist"
[[ "$(plutil -extract CFBundleShortVersionString raw -o - "$INFO")" == "$VERSION" ]] || die 'the app version does not match the release.'
codesign --verify --deep --strict "$APP" || die 'the app bundle failed its signature check.'
codesign --verify --strict -R='identifier "dev.local.steadfast" and certificate root = H"'"$CERT"'"' "$APP" || die 'the app does not match the steadfast release certificate.'
codesign --verify --strict -R='identifier "dev.local.steadfast.service" and certificate root = H"'"$CERT"'"' "$HELPER" || die 'the helper does not match the steadfast release certificate.'
printf 'verified steadfast %s and its background service.\n' "$VERSION"
if [[ "$VERIFY" == true ]]; then exit 0; fi

DEST=/Applications/Steadfast.app
if [[ "$IN_APP" == true ]]; then
  for ((attempt=0; attempt<10; attempt++)); do
    if ! pgrep -f "^$DEST/Contents/MacOS/Steadfast( |$)" >/dev/null; then break; fi
    sleep 1
  done
fi
if pgrep -f "^$DEST/Contents/MacOS/Steadfast( |$)" >/dev/null; then
  die 'quit steadfast, then run this command again.'
fi
if [[ -f "$DEST/Contents/Info.plist" ]]; then
  INSTALLED="$(plutil -extract CFBundleShortVersionString raw -o - "$DEST/Contents/Info.plist")"
  if [[ "$INSTALLED" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    newest="$(printf '%s\n%s\n' "$VERSION" "$INSTALLED" | sort -t . -k1,1nr -k2,2nr -k3,3nr | head -n 1)"
    [[ "$newest" == "$VERSION" ]] || die "steadfast $INSTALLED is newer than this release."
  fi
fi
FIRST_INSTALL=false
if [[ ! -x /Library/PrivilegedHelperTools/dev.local.steadfastd ]]; then FIRST_INSTALL=true; fi
printf 'steadfast installs a background service that blocks websites and apps, so blocks keep running after you quit.\n'
printf 'approve administrator access to install steadfast.\n'
/usr/bin/sudo /bin/bash -c '
  set -euo pipefail
  source_app="$1"
  cert="$2"
  stage="$(/usr/bin/mktemp -d /private/var/root/.steadfast-verify.XXXXXX)"
  trap '\''/bin/rm -rf "$stage"'\'' EXIT
  /usr/bin/ditto "$source_app" "$stage/Steadfast.app"
  /usr/sbin/chown -R root:wheel "$stage"
  /bin/chmod -R go-w "$stage"
  app="$stage/Steadfast.app"
  /usr/bin/codesign --verify --deep --strict "$app"
  /usr/bin/codesign --verify --strict -R "=identifier \"dev.local.steadfast\" and certificate root = H\"$cert\"" "$app"
  /usr/bin/codesign --verify --strict -R "=identifier \"dev.local.steadfast.service\" and certificate root = H\"$cert\"" "$app/Contents/Resources/steadfastd"
  /bin/bash "$app/Contents/Resources/Install.command" "$app"
' steadfast-install "$APP" "$CERT"
if [[ "$FIRST_INSTALL" == true ]]; then
  open -a "$DEST" --args --first-install
else
  open -a "$DEST"
fi
